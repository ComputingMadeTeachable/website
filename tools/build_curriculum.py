"""Build curriculum.html from tools/curriculum.json.

To add a unit: add an entry to "units" in curriculum.json (copy an existing one),
then run:  python3 tools/build_curriculum.py
Coverage levels: "Strong" (taught and assessed), "Partial" (some parts covered),
"Introduced" (foundations only). Leave a statement out of "coverage" if the unit
doesn't cover it.
"""
import json, html, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
D = json.loads((ROOT / "tools" / "curriculum.json").read_text())
e = html.escape
units = D["units"]
NONE = '<span class="none" aria-label="Not in this unit">–</span>'
TICK = '<span class="tick" aria-label="Yes">✓</span>'
LEVEL_CLASS = {"Strong": "lv-strong", "Partial": "lv-partial", "Introduced": "lv-intro"}


def unit_label(u):
    return f"Year {u['year']} · Unit {u['unit']}"


def badge(level):
    return f'<span class="lv {LEVEL_CLASS[level]}">{e(level)}</span>'


# ---------- coverage matrix ----------
head = "".join(
    f'<th scope="col" class="{"dev" if u["status"] != "available" else ""}">'
    f'<a href="#{u["id"]}">{e(unit_label(u))}</a><small>{e(u["title"])}'
    f'{"<br><em>In development</em>" if u["status"] != "available" else ""}</small></th>'
    for u in units)
rows = []
for s in D["statements"]:
    cells = []
    for u in units:
        c = u["coverage"].get(s["id"])
        cells.append(f'<td class="c">{badge(c[0]) if c else NONE}</td>')
    covered = any(s["id"] in u["coverage"] for u in units)
    later = "" if covered else '<span class="later">Coming in later units</span>'
    rows.append(
        f'<tr><th scope="row"><strong>{e(s["short"])}</strong>{later}'
        f'<details><summary>Full statement</summary><p>“{e(s["text"])}”</p></details></th>{"".join(cells)}</tr>')
matrix = f'<table class="map"><thead><tr><th scope="col">KS3 programme of study: pupils should be taught to…</th>{head}</tr></thead><tbody>{"".join(rows)}</tbody></table>'

# ---------- skills progression ----------
srows = []
for sk in D["skills"]:
    cells = "".join(
        f'<td class="c">{TICK if sk in u["skills"] else ""}</td>' for u in units)
    srows.append(f'<tr><th scope="row">{e(sk)}</th>{cells}</tr>')
shead = "".join(f'<th scope="col" class="{"dev" if u["status"] != "available" else ""}">{e(unit_label(u))}</th>' for u in units)
skills = f'<table class="map skills"><thead><tr><th scope="col">Skill</th>{shead}</tr></thead><tbody>{"".join(srows)}</tbody></table>'

# ---------- unit cards ----------
stext = {s["id"]: s["short"] for s in D["statements"]}
cards = []
for u in units:
    n = f' · {u["lessons_total"]} lessons' if u["lessons_total"] else ""
    tag = '<span class="tag dev">In development</span>' if u["status"] != "available" else '<span class="tag">Available now</span>'
    lessons = "".join(f'<li><span>{e(a)}</span>{e(b)}</li>' for a, b in u["lessons"])
    cov = "".join(
        f'<li>{badge(lv)} <strong>{e(stext[sid])}.</strong> {e(note)}</li>' for sid, (lv, note) in u["coverage"].items())
    cards.append(f"""
    <article class="unit" id="{u['id']}">
      <div class="unit-head">{tag}<p class="eyebrow">{e(unit_label(u))}{e(n)}</p>
        <h3>{e(u['title'])}</h3><p class="sub">{e(u['subtitle'])}</p></div>
      <p>{e(u['summary'])}</p>
      <h4>Lessons</h4><ol class="lessons">{lessons}</ol>
      <h4>National Curriculum coverage</h4><ul class="cov">{cov}</ul>
    </article>""")

